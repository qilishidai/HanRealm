def 资源索引(瓦片id):
    """City.getResourceIndex。"""
    if 瓦片id < 6 or 瓦片id > 11:
        return -1
    return 瓦片id - 6


def 建筑索引(瓦片id):
    """City.getBuildingIndex。"""
    if 瓦片id < 14:
        return -1
    if 瓦片id <= 20:
        return 瓦片id - 14
    if 瓦片id <= 26:
        return 瓦片id - 20
    return -1


